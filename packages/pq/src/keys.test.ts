import { test, expect } from 'bun:test';
import { ml_dsa44 } from '@noble/post-quantum/ml-dsa.js';
import { bytesToHex, keccak256 } from 'viem';
import { derivePQSeed, prepareMLDSA, c10Keygen, c10Sign, type C10Wasm } from './keys';
test('HKDF PQ domains and fixed-width account/index/epoch are separate and reproducible', () => {
  const seed = new Uint8Array(64),
    a = derivePQSeed(seed, 'mldsa44');
  expect(bytesToHex(a)).toBe('0x5ebba016a4b1f7a6f81c8b6ffd350a2c2fd7f48122726fa4ab23fa132623e904');
  for (const v of [
    derivePQSeed(seed, 'c10').slice(0, 32),
    derivePQSeed(seed, 'mldsa44', 1),
    derivePQSeed(seed, 'mldsa44', 0, 1),
    derivePQSeed(seed, 'mldsa44', 0, 0, 1),
  ])
    expect(v).not.toEqual(a);
  expect(() => derivePQSeed(new Uint8Array(32), 'mldsa44')).toThrow();
  expect(() => derivePQSeed(seed, 'c10', -1)).toThrow();
  expect(derivePQSeed(seed, 'c10').length).toBe(48);
  expect(derivePQSeed(seed, 'mldsa44', 0xffffffff, 0xffffffff, 0xffffffff).length).toBe(32);
  for (const value of [-1, 0.5, 0x1_0000_0000, Number.NaN, Number.POSITIVE_INFINITY]) {
    expect(() => derivePQSeed(seed, 'c10', value)).toThrow('path');
    expect(() => derivePQSeed(seed, 'mldsa44', 0, value)).toThrow('path');
    expect(() => derivePQSeed(seed, 'mldsa44', 0, 0, value)).toThrow('path');
  }
  expect(derivePQSeed(seed, 'mldsa44', 1, 0, 0)).not.toEqual(
    derivePQSeed(seed, 'mldsa44', 0, 1, 0),
  );
});
test('MLDSA real KeyGen + exact Python prepare differential; known degenerate keys rejected', async () => {
  const keys = ml_dsa44.keygen(new Uint8Array(32)),
    blob = prepareMLDSA(keys.publicKey);
  expect(keys.publicKey.length).toBe(1312);
  expect(blob.length).toBe(20545);
  // Independently generated by pinned Fireblocks prepare.py for KeyGen_internal(00*32).
  expect(keccak256(bytesToHex(blob))).toBe(
    '0xeab86422c3acade3a03a9f0aa4fb16b4f5806d99102eb8316ceddb444675a3bf',
  );
  const message = new Uint8Array(32),
    sig = ml_dsa44.sign(message, keys.secretKey);
  expect(sig.length).toBe(2420);
  expect(ml_dsa44.verify(sig, message, keys.publicKey)).toBe(true);
  message[0] = 1;
  expect(ml_dsa44.verify(sig, message, keys.publicKey)).toBe(false);
  const fixtureMessage = new Uint8Array(32).fill(2);
  expect(
    new Uint8Array(await Bun.file('packages/pq/test-vectors/mldsa-public-test.blob').arrayBuffer()),
  ).toEqual(blob);
  const fixtureSignature = new Uint8Array(
    await Bun.file('packages/pq/test-vectors/mldsa-public-test.sig').arrayBuffer(),
  );
  expect(ml_dsa44.verify(fixtureSignature, fixtureMessage, keys.publicKey)).toBe(true);
  for (const v of [0, 255]) {
    const pk = new Uint8Array(1312).fill(v);
    expect(() => prepareMLDSA(pk)).toThrow('Degenerate');
  }
  expect(() => prepareMLDSA(new Uint8Array(1311))).toThrow();
});
test('C10 WASM matches pinned Python and native Rust signature, no host imports', async () => {
  const bytes = await Bun.file('apps/web/src/pq/generated/c10.wasm').arrayBuffer(),
    module = await WebAssembly.compile(bytes);
  expect(WebAssembly.Module.imports(module)).toEqual([]);
  const wasm = (await WebAssembly.instantiate(module)).exports as C10Wasm;
  expect(() => c10Sign(wasm, new Uint8Array(32).fill(2))).toThrow('failed');
  expect(() => c10Keygen(wasm, new Uint8Array(47))).toThrow();
  expect(bytesToHex(c10Keygen(wasm, new Uint8Array(48).fill(1)))).toBe(
    '0x0101010101010101010101010101010142091ce501796f008e9b5ac204f2beb6',
  );
  expect(c10Sign(wasm, new Uint8Array(32).fill(2))).toEqual(
    new Uint8Array(await Bun.file('packages/pq/test-vectors/c10-public-test.sig').arrayBuffer()),
  );
  expect(() => c10Sign(wasm, new Uint8Array(31))).toThrow();
});
